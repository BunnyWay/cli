import { readdirSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { detectDeno } from "./deno.ts";
import { detectDotnet } from "./dotnet.ts";
import { detectGo } from "./go.ts";
import { detectJava } from "./java.ts";
import { detectNode } from "./node.ts";
import { detectPhp } from "./php.ts";
import type { DetectedApp, Detector, Project } from "./project.ts";
import { detectPython } from "./python.ts";
import { detectRuby } from "./ruby.ts";
import { detectRust } from "./rust.ts";

/**
 * Detect the app at a project root and render a Dockerfile for it, so
 * `bunny apps deploy` works in a repo that has none. The generated file is
 * the user's from then on; deploys build it like any other Dockerfile.
 */

export type { DetectedApp, Project } from "./project.ts";

// Manifest-led stacks first. Node goes last: PHP, Ruby, Python and the
// rest often carry a package.json for frontend assets, and a lone
// index.js is the weakest signal.
const DETECTORS: Detector[] = [
  detectPhp,
  detectRuby,
  detectPython,
  detectGo,
  detectRust,
  detectDotnet,
  detectJava,
  detectDeno,
  detectNode,
];

export function detectAppFrom(project: Project): DetectedApp | undefined {
  for (const detect of DETECTORS) {
    const app = detect(project);
    if (app) return app;
  }
  return undefined;
}

export function detectApp(root: string): DetectedApp | undefined {
  const list = (path: string) => {
    try {
      return readdirSync(join(root, path));
    } catch {
      return [];
    }
  };
  return detectAppFrom({
    entries: list(""),
    list,
    read: (path) => {
      try {
        return readFileSync(join(root, path), "utf-8");
      } catch {
        return null;
      }
    },
  });
}

// Never in an image: `.env` files (`bunny apps env` sets them at runtime),
// and bunny config, which a server of the project root (plain PHP) would
// otherwise publish.
const PRIVATE = [".env", ".env.*", "bunny.jsonc", ".bunny"];

/**
 * The `.dockerignore` to write: a new one for the stack, or the user's
 * `existing` file with any missing private entries appended. Undefined
 * when the existing file already covers them.
 */
export function dockerignore(
  app: DetectedApp,
  existing?: string,
): string | undefined {
  if (existing === undefined) {
    return `${[
      "# Generated by the bunny CLI.",
      ".git",
      ".env",
      ".env.*",
      "!.env.example",
      "bunny.jsonc",
      ".bunny",
      "Dockerfile",
      ".dockerignore",
      ...app.ignore,
    ].join("\n")}\n`;
  }

  const have = new Set(existing.split("\n").map((line) => line.trim()));
  const missing = PRIVATE.filter((line) => !have.has(line));
  if (missing.length === 0) return undefined;
  // `.env.*` would also hide the example file, which is safe to ship.
  if (missing.includes(".env.*")) missing.push("!.env.example");
  return `${existing.trimEnd()}\n\n# Added by the bunny CLI: keep secrets and bunny config out of the image.\n${missing.join("\n")}\n`;
}
