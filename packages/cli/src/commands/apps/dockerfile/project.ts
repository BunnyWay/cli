/** What a stack detector reads from the project root. */
export interface Project {
  /** Names of the files and directories at the project root. */
  entries: readonly string[];
  /** Text of a file relative to the root, or null when it can't be read. */
  read(path: string): string | null;
  /** Names in a directory relative to the root, or [] when it can't be read. */
  list(path: string): string[];
}

/** A detected app and the Dockerfile that builds and runs it. */
export interface DetectedApp {
  /** Framework or language, e.g. "Next.js" or "Go". */
  label: string;
  /** Port the server listens on by default. */
  port: number;
  /** App name suggested by the project manifest. */
  name?: string;
  /** `.dockerignore` lines for the stack's dependency and build directories. */
  ignore: string[];
  /** Render the Dockerfile with the server on `port`. */
  dockerfile(port: number): string;
}

export type Detector = (project: Project) => DetectedApp | undefined;

export function readJson(
  project: Project,
  path: string,
): Record<string, unknown> | null {
  try {
    const value = JSON.parse(project.read(path) ?? "null");
    return value && typeof value === "object" ? value : null;
  } catch {
    return null;
  }
}

/** App name from a package name: `@scope/app` or `vendor/app` → `app`. */
export function appName(name: unknown): string | undefined {
  return typeof name === "string"
    ? name.split("/").pop() || undefined
    : undefined;
}

/** First capture of `pattern` across `sources`, or `fallback`. */
export function versionFrom(
  sources: (string | null | undefined)[],
  pattern: RegExp,
  fallback: string,
): string {
  for (const source of sources) {
    const match = source?.match(pattern)?.[1];
    if (match) return match;
  }
  return fallback;
}

/** Join Dockerfile lines under the generated-file header. */
export function dockerfile(label: string, lines: string[]): string {
  return `${[
    `# Generated by \`bunny apps deploy\` for ${label}. Edit freely: deploys build this file as-is.`,
    ...lines,
  ].join("\n")}\n`;
}
