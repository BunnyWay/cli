// The published router source's generation; recorded in site state so deploy republishes routers that predate the current source.
export const ROUTER_VERSION = 6;

// The site's middleware Edge Script. It maps the site's hosts to the published deploy dir, and it serves the deploy's own `404.html`, `_redirects` and `_headers`. Those three names are the whole contract with a framework: Cloudflare Pages and Netlify read the same ones, so nothing here knows about any framework, and every preset gets the same behaviour.
//
// The edge hands the script an origin-facing URL (an internal `ip:9000` address), so the client hostname MUST come from the CDN-Host/Host headers; matching on `url.hostname` silently routes every request wrong. The deploy's configuration is read at run time and held in memory, never inlined below, so a publish stays an environment variable change.
//
// The zone's `CacheControlMaxAgeOverride` is off (see `STATIC_SITE_ZONE_SETTINGS`), which means whatever this script returns is what the visitor gets. So every response leaves here with a `Cache-Control`, because Bunny Storage sends none for HTML.
//
// (See AGENTS.md and the SOURCE comments below; BunnySDK hook and header names are the platform contract.)
export const routerSource = `// bunny sites router v${ROUTER_VERSION}, generated by the bunny CLI. Do not edit:
// \`bunny sites upgrade-router\` overwrites this script.
import * as BunnySDK from "@bunny.net/edgescript-sdk";

const RETRY_HEADER = "x-bunny-index-retry";
// The path the client asked for, carried to the response phase: by then the URL is the rewritten origin one, and \`_redirects\` and \`_headers\` are written against what the visitor typed.
const PATH_HEADER = "x-bunny-path";
// Marks a request this router made for itself, so the response phase adds nothing to it and cannot recurse through it.
const RAW_HEADER = "x-bunny-raw";

// The files a deploy configures the router with. Host-standard names: Cloudflare Pages and Netlify read the same ones, so a framework that already writes them needs nothing new. The router reads them through its own reserved path, which is the whole permission: nothing else under \`_bunny/\` becomes reachable.
const CONFIG_PATH = "/_bunny/router/";
const CONFIG_FILES = ["_redirects", "_headers", "404.html", "404/index.html"];

// A page is rewritten in place by the next deploy, so a browser may only keep it briefly; a publish purges the edge. Everything else is content a new deploy renames, and \`_headers\` is where a build says which directory is hashed.
const PAGE_CACHE = "public, max-age=60";
const ASSET_CACHE = "public, max-age=2592000";
// Extensions whose object is a document: entered by URL, and replaced in place.
const PAGE_EXT = /\\.(?:html?|json|xml|txt|rss|atom|webmanifest|map)$/i;
// A body these statuses may not carry. Constructing one with a body throws.
const BODYLESS = [101, 204, 205, 304];

// ctx.request.url carries the ORIGIN address at the edge, not the requested host; the platform passes the client hostname in CDN-Host (Host covers local harnesses).
function clientHostname(request) {
  const fromHeader =
    request.headers.get("cdn-host") ?? request.headers.get("host");
  return (fromHeader ?? new URL(request.url).hostname).toLowerCase();
}

const NO_DEPLOYS_PAGE = \`<!doctype html>
<title>No deploys yet</title>
<body style="font-family:system-ui,sans-serif;text-align:center;padding-top:4rem">
<h1>Nothing here yet 🐇</h1>
<p>Run <code>bunny sites deploy</code> to publish this site.</p>\`;

// A slashless URL's directory-index retry target (/blog -> /blog/) on the client host, so the probe re-enters the CDN (and this router) instead of hitting the storage origin's unrouted paths; null when the path already ends with a slash.
function indexRetryUrl(rawUrl, host) {
  const u = new URL(rawUrl);
  if (u.pathname.endsWith("/")) return null;
  return "https://" + host + u.pathname + "/" + u.search;
}

// The path a rule is matched against: no trailing slash, and never empty. \`/about/\` and \`/about\` are one page to every static host, so they are one rule here.
function matchPath(pathname) {
  const trimmed = pathname.replace(/\\/+$/, "");
  return trimmed === "" ? "/" : trimmed;
}

// Statuses a rule may ask for. A rewrite (\`200\`) is deliberately not one: it would have this router fetch another path of its own site, which can be made to loop, and no deploy needs it yet.
const REDIRECT_STATUS = [301, 302, 303, 307, 308];

// \`_redirects\`, in the subset Cloudflare Pages and Netlify agree on: \`from to [status]\` per line, \`#\` comments, a trailing \`*\` in \`from\` captured as \`:splat\`, and \`!\` after the status to beat a file at the same path.
function parseRedirects(text) {
  const rules = [];
  for (const raw of text.split("\\n")) {
    const line = raw.trim();
    if (line === "" || line.startsWith("#")) continue;
    const parts = line.split(/\\s+/);
    if (parts.length < 2) continue;
    const from = parts[0];
    const to = parts[1];
    if (!from.startsWith("/")) continue;
    const asked = parts[2] ?? "301";
    const status = Number.parseInt(asked.replace("!", ""), 10);
    if (!REDIRECT_STATUS.includes(status)) continue;
    rules.push({ from: matchPath(from), to, status, force: asked.endsWith("!") });
  }
  return rules;
}

// \`_headers\`: a line starting with \`/\` opens a block, and each \`Name: value\` line below it belongs to that block.
function parseHeaders(text) {
  const rules = [];
  let current = null;
  for (const raw of text.split("\\n")) {
    const line = raw.trim();
    if (line === "" || line.startsWith("#")) continue;
    if (line.startsWith("/")) {
      current = { from: matchPath(line), entries: [] };
      rules.push(current);
      continue;
    }
    if (!current) continue;
    const colon = line.indexOf(":");
    if (colon < 1) continue;
    const name = line.slice(0, colon).trim();
    const value = line.slice(colon + 1).trim();
    if (name !== "" && value !== "") current.entries.push([name, value]);
  }
  return rules.filter((rule) => rule.entries.length > 0);
}

// What a trailing \`*\` in the rule's path captured, "" for an exact match, or null when the rule does not apply.
function ruleSplat(from, path) {
  if (!from.endsWith("*")) return from === path ? "" : null;
  const prefix = from.slice(0, -1);
  return path.startsWith(prefix) ? path.slice(prefix.length) : null;
}

// The first rule that matches, with \`:splat\` filled in.
function matchRedirect(rules, path, forcedOnly) {
  for (const rule of rules) {
    if (forcedOnly && !rule.force) continue;
    const splat = ruleSplat(rule.from, path);
    if (splat === null) continue;
    return { ...rule, to: rule.to.replaceAll(":splat", splat) };
  }
  return null;
}

// Every header the matching blocks ask for, in file order, so a later block overrides an earlier one on the same name.
function matchHeaders(rules, paths) {
  const found = new Map();
  for (const rule of rules) {
    if (!paths.some((path) => ruleSplat(rule.from, path) !== null)) continue;
    for (const [name, value] of rule.entries) {
      found.set(name.toLowerCase(), value);
    }
  }
  return found;
}

// What a response may be cached for when \`_headers\` says nothing. The pull zone's own override is off on a sites zone, so this is the answer the visitor gets.
function defaultCacheControl(path) {
  return PAGE_EXT.test(path) || !path.includes(".") ? PAGE_CACHE : ASSET_CACHE;
}

// Read one of the deploy's configuration files. "" means the deploy does not hold it, and null means it could not be read at all, which must not be remembered as "no rules".
async function readFile(host, name) {
  try {
    const response = await fetch("https://" + host + CONFIG_PATH + name, {
      headers: { [RAW_HEADER]: "1" },
    });
    if (response.status === 404) return "";
    return response.ok ? await response.text() : null;
  } catch {
    return null;
  }
}

// The deploy's rules, read once and held for the life of the isolate. They are never inlined in this script, so a publish stays an environment variable change.
const configs = new Map();

function readConfig(host, deploy) {
  const held = configs.get(deploy);
  if (held) return held;
  const loading = (async () => {
    const [redirects, headers, page, nested] = await Promise.all([
      readFile(host, "_redirects"),
      readFile(host, "_headers"),
      readFile(host, "404.html"),
      readFile(host, "404/index.html"),
    ]);
    // A read that failed is not an answer. Forget the lot and try again on the
    // next request, rather than serving a deploy without its rules for hours.
    if (redirects === null || headers === null) configs.delete(deploy);
    return {
      redirects: parseRedirects(redirects ?? ""),
      headers: parseHeaders(headers ?? ""),
      notFound: page || nested || null,
    };
  })();
  configs.set(deploy, loading);
  return loading;
}

BunnySDK.net.http
  .servePullZone()
  .onOriginRequest(async (ctx) => {
    const url = new URL(ctx.request.url);
    const host = clientHostname(ctx.request);
    const requested = url.pathname;

    // The router's own reads, which skip every rule below.
    const wanted = requested.startsWith(CONFIG_PATH)
      ? requested.slice(CONFIG_PATH.length)
      : null;

    // Storage serves no directory indexes: expand \`/dir/\` to \`/dir/index.html\` on every route.
    if (url.pathname.endsWith("/")) url.pathname += "index.html";
    const path = url.pathname;

    // Internal site metadata (state, env) is never served.
    if (wanted === null && (path === "/_bunny" || path.startsWith("/_bunny/"))) {
      return new Response("Forbidden", { status: 403 });
    }

    // Every flag is router-internal: client-sent copies are stripped, or they'd poison cached HTML.
    const headers = new Headers(ctx.request.headers);
    headers.delete(RETRY_HEADER);
    headers.delete(PATH_HEADER);
    headers.delete(RAW_HEADER);

    const deploy = process.env.CURRENT_DEPLOY || "";

    if (!deploy) {
      return new Response(NO_DEPLOYS_PAGE, {
        status: 404,
        headers: { "Content-Type": "text/html; charset=utf-8" },
      });
    }

    if (wanted !== null) {
      if (!CONFIG_FILES.includes(wanted)) {
        return new Response("Not Found", { status: 404 });
      }
      headers.set(RAW_HEADER, "1");
      url.pathname = "/deploys/" + deploy + "/" + wanted;
      return new Request(new Request(url.toString(), ctx.request), { headers });
    }

    headers.set(PATH_HEADER, requested);

    if (ctx.request.method === "GET" || ctx.request.method === "HEAD") {
      // A forced rule beats a file at the same path, so it is the only kind that can be answered before the origin is asked. An unforced one waits for the 404, which is what makes a real file win.
      const rules = await readConfig(host, deploy);
      const forced = matchRedirect(rules.redirects, matchPath(requested), true);
      if (forced) {
        return new Response(null, {
          status: forced.status,
          headers: { Location: forced.to, "Cache-Control": PAGE_CACHE },
        });
      }
      // Exact objects win: a slashless GET/HEAD miss retries as its directory index in the response phase.
      const retry = indexRetryUrl(ctx.request.url, host);
      if (retry) headers.set(RETRY_HEADER, retry);
    }

    url.pathname = "/deploys/" + deploy + path;
    return new Request(new Request(url.toString(), ctx.request), { headers });
  })
  .onOriginResponse(async (ctx) => {
    // The router's own read. Nothing is applied to it, and nothing recurses through it.
    if (ctx.request.headers.get(RAW_HEADER)) return;

    // Only a request this router sent to the origin carries the path, so only
    // one of those is answered here. A response the request phase produced by
    // itself (a forced redirect, a 403, an unpublished site) is already final.
    const requested = ctx.request.headers.get(PATH_HEADER);
    if (requested === null) return;

    const host = clientHostname(ctx.request);
    const deploy = process.env.CURRENT_DEPLOY || "";
    const rules = await readConfig(host, deploy);
    const response = ctx.response;

    if (response.status === 404) {
      // A flagged 404 probes its directory index and redirects to the slash URL when it exists (/blog -> /blog/), so relative references resolve against the right base; the probe re-enters this router and, slash-terminated, can never retry further.
      const retry = ctx.request.headers.get(RETRY_HEADER);
      if (retry) {
        const probe = await fetch(retry, { method: "HEAD" });
        if (probe.ok) {
          return new Response(null, {
            status: 301,
            headers: { Location: retry },
          });
        }
      }

      const rule = matchRedirect(rules.redirects, matchPath(requested), false);
      if (rule) {
        return new Response(null, {
          status: rule.status,
          headers: { Location: rule.to, "Cache-Control": PAGE_CACHE },
        });
      }

      // The deploy's own 404 page. Without this the CDN answers a miss with bunny.net's page, whatever the site built.
      if (rules.notFound !== null) {
        return new Response(rules.notFound, {
          status: 404,
          headers: {
            "Content-Type": "text/html; charset=utf-8",
            // A miss the next deploy fixes must not outlive it.
            "Cache-Control": "no-cache",
          },
        });
      }
    }

    // Bunny Storage holds no headers, so \`_headers\` is where the deploy keeps them. The requested path and the object it resolved to are both matched, so a rule may be written either way.
    const headers = new Headers(response.headers);
    const paths = [matchPath(requested)];
    if (requested.endsWith("/")) {
      paths.push(matchPath(requested + "index.html"));
    }
    for (const [name, value] of matchHeaders(rules.headers, paths)) {
      headers.set(name, value);
    }

    // The pull zone applies no expiry of its own to a sites zone, so a response carrying no directive would reach the visitor with none.
    if (!headers.has("Cache-Control")) {
      headers.set("Cache-Control", defaultCacheControl(requested));
    }

    return new Response(BODYLESS.includes(response.status) ? null : response.body, {
      status: response.status,
      statusText: response.statusText,
      headers,
    });
  });
`;
