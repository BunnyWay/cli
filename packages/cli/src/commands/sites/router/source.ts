// The site's middleware Edge Script: maps the apex to the published deploy dir and `dpl-{id}.preview.*` hosts to theirs (see AGENTS.md and the SOURCE comments below). BunnySDK hook names are the platform contract.
export const routerSource = `// bunny sites router, generated by the bunny CLI. Do not edit:
// \`bunny sites upgrade-router\` overwrites this script.
import * as BunnySDK from "@bunny.net/edgescript-sdk";

const PREVIEW_HOST = /^dpl-([a-z0-9]{4,40})\\.preview\\./i;
const RETRY_HEADER = "x-bunny-index-retry";

const NO_DEPLOYS_PAGE = \`<!doctype html>
<html><head><meta charset="utf-8"><title>No deploys yet</title></head>
<body style="font-family: system-ui, sans-serif; text-align: center; padding-top: 4rem">
<h1>Nothing here yet 🐇</h1>
<p>This site has no published deploys. Run <code>bunny sites deploy</code> to publish one.</p>
</body></html>\`;

// A slashless URL's directory-index retry target (/blog -> /blog/); null when the path already ends with a slash.
function indexRetryUrl(rawUrl) {
  const u = new URL(rawUrl);
  if (u.pathname.endsWith("/")) return null;
  u.pathname += "/";
  return u.toString();
}

BunnySDK.net.http
  .servePullZone()
  .onOriginRequest(async (ctx) => {
    const url = new URL(ctx.request.url);
    // Storage serves no directory indexes: expand \`/dir/\` to \`/dir/index.html\` on every route.
    if (url.pathname.endsWith("/")) url.pathname += "index.html";
    const path = url.pathname;

    // Internal site metadata (state, env) is never served.
    if (path === "/_bunny" || path.startsWith("/_bunny/")) {
      return new Response("Forbidden", { status: 403 });
    }

    // The flag is router-internal: client-sent copies are stripped, or they'd poison cached HTML.
    const headers = new Headers(ctx.request.headers);
    headers.delete(RETRY_HEADER);

    // Exact objects win: a slashless GET/HEAD miss retries as its directory index in the response phase.
    if (ctx.request.method === "GET" || ctx.request.method === "HEAD") {
      const retry = indexRetryUrl(ctx.request.url);
      if (retry) headers.set(RETRY_HEADER, retry);
    }

    const preview = PREVIEW_HOST.exec(url.hostname);
    const deploy = preview
      ? preview[1].toLowerCase()
      : process.env.CURRENT_DEPLOY || "";

    if (!deploy) {
      return new Response(NO_DEPLOYS_PAGE, {
        status: 404,
        headers: { "Content-Type": "text/html; charset=utf-8" },
      });
    }

    url.pathname = "/deploys/" + deploy + path;
    return new Request(new Request(url.toString(), ctx.request), { headers });
  })
  .onOriginResponse(async (ctx) => {
    // A flagged 404 probes its directory index and redirects to the slash URL when it exists (/blog -> /blog/), so relative references resolve against the right base; the probe re-enters this router and, slash-terminated, can never retry further.
    const retry = ctx.request.headers.get(RETRY_HEADER);
    if (retry && ctx.response.status === 404) {
      const probe = await fetch(retry, { method: "HEAD" });
      if (probe.ok) {
        return new Response(null, { status: 301, headers: { Location: retry } });
      }
    }

    // Previews must never be indexed.
    if (!PREVIEW_HOST.test(new URL(ctx.request.url).hostname)) return;
    const headers = new Headers(ctx.response.headers);
    headers.set("X-Robots-Tag", "noindex");
    return new Response(ctx.response.body, {
      status: ctx.response.status,
      statusText: ctx.response.statusText,
      headers,
    });
  });
`;
