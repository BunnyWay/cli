/**
 * The site router — a middleware Edge Script attached to the site's pull zone.
 *
 * It maps incoming hosts to deploy directories inside the storage-zone origin:
 *
 * - apex / `.b-cdn.net` host        → `/deploys/{CURRENT_DEPLOY}{path}` (production)
 * - `dpl-{id}.preview.{domain}`     → `/deploys/{id}{path}` (custom-domain preview, root-served)
 * - `/deploys/{id}/...` paths       → passed through (immutable per-deploy preview URL)
 * - `/_bunny/*`                     → 403 (site state/env are never served)
 *
 * A path preview (`/deploys/{id}/`) serves a build under a subpath, so its
 * root-absolute asset URLs (`/assets/x.css`) would otherwise escape the prefix
 * and 404. The response phase runs such HTML through {@link HTMLRewriter} to
 * rewrite those refs to `/deploys/{id}/…` — the fix for Jekyll/most SSGs without
 * a custom domain, on a single pull zone (each deploy's assets get a unique URL,
 * so the CDN caches them separately). The request phase flags previews with an
 * `x-bunny-preview` header so production HTML (served at the apex) is never
 * rewritten — that would leak deploy ids into production URLs and churn its cache
 * on every promote.
 *
 * Promote/rollback is just a `CURRENT_DEPLOY` env write — the code never changes
 * between deploys. `sites upgrade-router` republishes this source onto a site.
 */

// NOTE: validated by the Phase 0 spike against the live platform; the exact
// BunnySDK middleware hook + HTMLRewriter names are the platform contract.
const SOURCE = `// bunny sites router — generated by the bunny CLI. Do not edit:
// \`bunny sites upgrade-router\` overwrites this script.
import * as BunnySDK from "@bunny.net/edgescript-sdk";

const PREVIEW_HOST = /^dpl-([a-z0-9]{4,40})\\.preview\\./i;
const PREVIEW_HEADER = "x-bunny-preview";
const DEPLOY_PATH = /^\\/deploys\\/([a-z0-9]{4,40})\\//i;

const NO_DEPLOYS_PAGE = \`<!doctype html>
<html><head><meta charset="utf-8"><title>No deploys yet</title></head>
<body style="font-family: system-ui, sans-serif; text-align: center; padding-top: 4rem">
<h1>Nothing here yet 🐇</h1>
<p>This site has no published deploys. Run <code>bunny sites deploy</code> to publish one.</p>
</body></html>\`;

// Prefix root-absolute, un-prefixed paths with the deploy dir; leave everything else alone.
function withDeploy(id, value) {
  if (!value || value[0] !== "/" || value[1] === "/") return value;
  if (value.startsWith("/deploys/")) return value;
  return "/deploys/" + id + value;
}

function rewriteAttr(id, attr) {
  return {
    element(el) {
      const v = el.getAttribute(attr);
      if (v) el.setAttribute(attr, withDeploy(id, v));
    },
  };
}

function rewriteSrcset(id) {
  return {
    element(el) {
      const v = el.getAttribute("srcset");
      if (!v) return;
      const out = v
        .split(",")
        .map((part) => {
          const seg = part.trim().split(/\\s+/);
          seg[0] = withDeploy(id, seg[0]);
          return seg.join(" ");
        })
        .join(", ");
      el.setAttribute("srcset", out);
    },
  };
}

BunnySDK.net.http
  .servePullZone()
  .onOriginRequest(async (ctx) => {
    const url = new URL(ctx.request.url);
    const path = url.pathname;

    // Internal site metadata (state, env) is never served.
    if (path === "/_bunny" || path.startsWith("/_bunny/")) {
      return new Response("Forbidden", { status: 403 });
    }

    // Path preview: flag the request so the response phase rewrites its HTML for this deploy.
    if (path === "/deploys" || path.startsWith("/deploys/")) {
      const match = DEPLOY_PATH.exec(path);
      if (!match) return;
      const headers = new Headers(ctx.request.headers);
      headers.set(PREVIEW_HEADER, match[1].toLowerCase());
      return new Request(ctx.request, { headers });
    }

    const preview = PREVIEW_HOST.exec(url.hostname);
    const deploy = preview
      ? preview[1].toLowerCase()
      : process.env.CURRENT_DEPLOY || "";

    if (!deploy) {
      return new Response(NO_DEPLOYS_PAGE, {
        status: 404,
        headers: { "Content-Type": "text/html; charset=utf-8" },
      });
    }

    let target = path;
    if (target.endsWith("/")) target += "index.html";
    url.pathname = "/deploys/" + deploy + target;
    return new Request(url.toString(), ctx.request);
  })
  .onOriginResponse(async (ctx) => {
    const previewId = ctx.request.headers.get(PREVIEW_HEADER);
    const isCustomPreview = PREVIEW_HOST.test(new URL(ctx.request.url).hostname);
    if (!previewId && !isCustomPreview) return;

    let response = ctx.response;

    // Path previews serve under a subpath: rewrite root-absolute asset refs into the deploy.
    const contentType = response.headers.get("content-type") || "";
    if (previewId && contentType.includes("text/html")) {
      response = new HTMLRewriter()
        .on("a[href]", rewriteAttr(previewId, "href"))
        .on("link[href]", rewriteAttr(previewId, "href"))
        .on("script[src]", rewriteAttr(previewId, "src"))
        .on("img[src]", rewriteAttr(previewId, "src"))
        .on("img[srcset]", rewriteSrcset(previewId))
        .on("source[src]", rewriteAttr(previewId, "src"))
        .on("source[srcset]", rewriteSrcset(previewId))
        .transform(response);
    }

    // Previews must never be indexed.
    const headers = new Headers(response.headers);
    headers.set("X-Robots-Tag", "noindex");
    return new Response(response.body, {
      status: response.status,
      statusText: response.statusText,
      headers,
    });
  });
`;

/** The site's middleware router script. */
export function routerSource(): string {
  return SOURCE;
}
