import * as z from "zod/mini";

const MAX_STRING = 200;

/** Free text is cut to `MAX_STRING` rather than rejected. */
const text = z.pipe(
  z.string(),
  z.transform((value: string) => value.slice(0, MAX_STRING)),
);

/** Props every event may carry. */
const common = {
  cli_version: text,
  os: text,
  arch: text,
  ci: z.boolean(),
};

/** UUIDs of any version, in the 8-4-4-4-12 hex form. */
const uuid = z.guid();

function event<Name extends string, Props extends z.core.$ZodShape>(
  name: Name,
  props: Props,
) {
  return z.object({
    event: z.literal(name),
    /** Unique to this event; resending the same ID does not double count. */
    id: uuid,
    /** Stable for the install, generated by the CLI. */
    anon_id: uuid,
    /** When it happened, in Unix milliseconds. Events over 5 days off are dropped. */
    time: z.number(),
    /** Unknown props are stripped; a known prop of the wrong type fails the event. */
    props: z.nullish(z.partial(z.object({ ...common, ...props }))),
  });
}

const action = z.enum(["create", "update", "delete", "upload", "fetch"]);

/** One entry of the JSON array posted to `EVENTS_PATH`; an event or prop not declared here is dropped. */
export const CliEvent = z.discriminatedUnion("event", [
  event("command", {
    command: text,
    flags: text,
    result: z.enum(["success", "user_error", "api_error", "error"]),
    status: z.number(),
    duration_ms: z.number(),
    output: text,
  }),
  event("login", {}),
  event("stream_library", { action }),
  event("stream_video", {
    action,
    size_bytes: z.number(),
    resumable: z.boolean(),
  }),
  event("stream_collection", { action }),
  event("stream_import", {
    source: text,
    import_status: z.enum(["in_progress", "completed", "failed", "paused"]),
    videos: z.number(),
    failed: z.number(),
  }),
]);

export type CliEvent = z.infer<typeof CliEvent>;
export type EventName = CliEvent["event"];
const commonProps = z.object(common);
export type CommonProps = z.infer<typeof commonProps>;

/** The props specific to one event, for typing the CLI's `track()`. */
export type EventProps<E extends EventName> = Omit<
  NonNullable<Extract<CliEvent, { event: E }>["props"]>,
  keyof CommonProps
>;

/** The version lives in the path: a breaking change to the request or response gets a new path. */
export const EVENTS_PATH = "/v1/events";
/** The collector only accepts requests whose User-Agent starts with this. */
export const USER_AGENT_PREFIX = "bunny-cli/";
export const MAX_BODY_BYTES = 16_384;
/** Events past this count in one batch are dropped. */
export const MAX_EVENTS = 20;
